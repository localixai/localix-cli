"""Records an eval run into benchmarks/: one dated JSON per run, a regenerated HISTORY.md, and the
metrics block in README.md, so progress (pass rate, speed, cost, binary) is visible over time.

Called by run.py --record; can also re-render from existing runs: python3 evals/record.py
"""
import json, os, platform, statistics as st, subprocess, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNS = os.path.join(ROOT, "benchmarks", "runs")
README_START, README_END = "<!-- metrics:start -->", "<!-- metrics:end -->"


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    except OSError:
        return ""


def version():
    """`0.1.0` from Cargo.toml, with the commit (and `+dirty`) when there is one."""
    cargo = open(os.path.join(ROOT, "Cargo.toml")).read()
    number = cargo.split('version = "', 1)[1].split('"', 1)[0]
    commit = git("rev-parse", "--short", "HEAD")
    dirty = "+dirty" if git("status", "--porcelain") else ""
    return f"{number} ({commit}{dirty})" if commit else f"{number} (uncommitted)"


def cli_metrics(binary):
    """What the binary costs on its own: start, cold start to a first snapshot, memory, size."""
    def best(args, n):
        times = []
        for _ in range(n):
            started = time.time()
            subprocess.run([binary, *args], capture_output=True)
            times.append(time.time() - started)
        return round(min(times) * 1000, 1)

    cold = best(["x", "--url", "https://example.com", "--dry-run", "--headless"], 3)
    return {
        "binary_mb": round(os.path.getsize(binary) / 1048576, 2),
        "start_ms": best(["--version"], 5),
        "cold_snapshot_ms": cold,
        "rss_mb": peak_memory(binary),
    }


def peak_memory(binary):
    """Peak resident memory of one dry run, from /usr/bin/time (bytes on macOS, KB on Linux)."""
    flag = "-l" if sys.platform == "darwin" else "-v"
    proc = subprocess.run(["/usr/bin/time", flag, binary, "x", "--url", "https://example.com", "--dry-run", "--headless"],
                          capture_output=True, text=True)
    for line in proc.stderr.splitlines():
        if "maximum resident set size" in line.lower():
            number = int("".join(c for c in line if c.isdigit()))
            return round((number if sys.platform == "darwin" else number * 1024) / 1048576, 1)
    return None


def p90(values):
    values = sorted(values)
    return values[min(len(values) - 1, int(round(0.9 * (len(values) - 1))))] if values else 0


def summarize(results, binary, models):
    tasks = {}
    for r in results:
        tasks.setdefault(r["id"], []).append(r)
    walls = [r["wall"] for r in results]
    return {
        "date": time.strftime("%Y-%m-%d %H:%M"),
        "version": version(),
        "commit": git("rev-parse", "--short", "HEAD") or None,
        "host": f"{platform.system()} {platform.release()} {platform.machine()}",
        "models": models,
        "runs": len(results),
        "passed": sum(r["ok"] for r in results),
        "median_s": round(st.median(walls), 1) if walls else 0,
        "p90_s": round(p90(walls), 1),
        "cost_per_run": round(sum(r["cost"] for r in results) / max(1, len(results)), 5),
        "cli": cli_metrics(binary),
        "tasks": {
            task: {
                "runs": len(rs),
                "passed": sum(r["ok"] for r in rs),
                "median_s": round(st.median(r["wall"] for r in rs), 1),
                "tokens_per_decision": round(st.median(r.get("tokens_per_decision") or 0 for r in rs)),
                "jev_s": round(st.median(r.get("decision_s") or 0 for r in rs), 1),
                "web_s": round(st.median(r.get("browser_s") or 0 for r in rs), 1),
                "decisions": round(st.median(r.get("decisions") or 0 for r in rs), 1),
                "cost": round(st.median(r["cost"] for r in rs), 5),
            }
            for task, rs in tasks.items()
        },
    }


def load_runs():
    if not os.path.isdir(RUNS):
        return []
    return [json.load(open(os.path.join(RUNS, name))) for name in sorted(os.listdir(RUNS)) if name.endswith(".json")]


def trend(now, before, lower_is_better=True):
    if before is None or now == before:
        return ""
    better = now < before if lower_is_better else now > before
    return " ↓" if better == lower_is_better and now < before else (" ↑" if now > before else " ↓")


def render_history(runs):
    lines = [
        "# Benchmark history",
        "",
        "Generated by `evals/record.py` from `benchmarks/runs/` (one file per `python3 evals/run.py --record`). Do not edit by hand.",
        "",
        "| Date | Version | Passed | Median | p90 | $/run | Start | Cold snapshot | Binary |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for run in reversed(runs):
        cli = run.get("cli", {})
        lines.append(
            f"| {run['date']} | {run['version']} | {run['passed']}/{run['runs']} | {run['median_s']} s | {run['p90_s']} s | "
            f"${run['cost_per_run']:.4f} | {cli.get('start_ms')} ms | {cli.get('cold_snapshot_ms')} ms | {cli.get('binary_mb')} MB |"
        )
    if runs:
        latest = runs[-1]
        previous = runs[-2] if len(runs) > 1 else None
        lines += ["", f"## Tasks, {latest['date']}" + (f" (vs {previous['date']})" if previous else ""), "",
                  "| Task | Passed | Median | Jev | Web | Decisions | Tokens/decision | Cost |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for task, t in latest["tasks"].items():
            before = (previous or {}).get("tasks", {}).get(task)
            was = f" (was {before['median_s']} s)" if before and before["median_s"] != t["median_s"] else ""
            lines.append(f"| {task} | {t['passed']}/{t['runs']} | {t['median_s']} s{was} | {t['jev_s']} s | "
                         f"{t['web_s']} s | {t['decisions']} | {t.get('tokens_per_decision', '')} | ${t['cost']:.4f} |")
    return "\n".join(lines) + "\n"


def render_readme_block(run):
    cli = run.get("cli", {})
    models = run.get("models", {})
    return "\n".join([
        README_START,
        f"Latest run, {run['date']} on {run['host']}: the decision loop with {models.get('decision')}, "
        f"from [benchmarks/HISTORY.md](benchmarks/HISTORY.md):",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Eval tasks passed | {run['passed']}/{run['runs']} ({len(run['tasks'])} tasks) |",
        f"| Task time, median / p90 | {run['median_s']} s / {run['p90_s']} s |",
        f"| Cost per task | ${run['cost_per_run']:.4f} |",
        f"| Start (`--version`) | {cli.get('start_ms')} ms |",
        f"| Cold start to first snapshot (example.com) | {cli.get('cold_snapshot_ms')} ms |",
        f"| Process memory | {cli.get('rss_mb')} MB |",
        f"| Release binary | {cli.get('binary_mb')} MB |",
        README_END,
    ])


def write_all(runs):
    os.makedirs(RUNS, exist_ok=True)
    with open(os.path.join(ROOT, "benchmarks", "HISTORY.md"), "w") as f:
        f.write(render_history(runs))
    if not runs:
        return
    readme_path = os.path.join(ROOT, "README.md")
    readme = open(readme_path).read()
    block = render_readme_block(runs[-1])
    if README_START in readme:
        start, end = readme.index(README_START), readme.index(README_END) + len(README_END)
        readme = readme[:start] + block + readme[end:]
    open(readme_path, "w").write(readme)


def record(results, binary, models):
    run = summarize(results, binary, models)
    os.makedirs(RUNS, exist_ok=True)
    name = run["date"].replace(" ", "-").replace(":", "") + ".json"
    with open(os.path.join(RUNS, name), "w") as f:
        json.dump(run, f, indent=1, ensure_ascii=False)
    write_all(load_runs())
    return os.path.join(RUNS, name)


if __name__ == "__main__":
    write_all(load_runs())
